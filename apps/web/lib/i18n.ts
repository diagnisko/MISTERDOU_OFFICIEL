const DICTIONARIES: Record<Locale, Dictionary> = { fr, en, ar };

/** Locale BCP 47 pour les dates et nombres. */
export const INTL_LOCALE: Record<Locale, string> = { fr: "fr-FR", en: "en-GB", ar: "ar-SN" };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = DICTIONARIES[locale][key] ?? fr[key];
  return vars ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? "")) : template;
}

/** `t("clé", { variable })` dans la langue choisie. */
export function useT() {
  const { locale } = usePreferences();
  const t = useCallback((key: MessageKey, vars?: Record<string, string | number>) => translate(locale, key, vars), [locale]);
  return Object.assign(t, { locale, intl: INTL_LOCALE[locale] });
}
